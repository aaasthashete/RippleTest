"""JSON export of a run. Contains only actual records and honest metadata."""

from __future__ import annotations

import math
from typing import Any

from .differential import CaseResult, Outcome
from .pipeline import RunRecord

LIMITATIONS = (
    "A behavioural difference may be intentional. No difference found does not "
    "prove the change is regression-free.",
    "Only bundled, pre-reviewed functions were executed. Model-generated text is "
    "data, never code.",
    "The recorded values come from real Python execution; the model only proposed inputs.",
)


def _safe_value(value: Any) -> Any:
    if isinstance(value, bool) or value is None:
        return value
    if isinstance(value, (int, str)):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else repr(value)
    return repr(value)


def _outcome(outcome: Outcome) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "kind": outcome.kind,
        "display": outcome.display,
    }
    if outcome.kind == "value":
        payload["value"] = _safe_value(outcome.value)
        payload["value_type"] = type(outcome.value).__name__
    else:
        payload["exception_type"] = outcome.exception_type
        payload["exception_message"] = outcome.exception_message
    return payload


def _case(case: CaseResult) -> dict[str, Any]:
    return {
        "number": case.number,
        "arguments": {name: _safe_value(value) for name, value in case.arguments.items()},
        "original": _outcome(case.original),
        "modified": _outcome(case.modified),
        "classification": case.classification,
        "numeric_delta": case.delta,
        "note": case.note,
        "rationale": case.reason,
        "provenance": case.provenance,
    }


def run_report(run: RunRecord) -> dict[str, Any]:
    """Build a serialisable report whose counts match the executed records."""
    summary = run.summary
    return {
        "tool": "RippleTest",
        "generated_at": run.created_at,
        "scenario": {
            "id": run.scenario_id,
            "label": run.scenario_label,
            "function": run.function_name,
        },
        "input_provenance": (
            "AI-generated by the local model" if run.provenance == "ai" else "Curated baseline (not AI-generated)"
        ),
        "model": run.model or "none (curated baseline)",
        "model_request_seconds": run.duration_seconds,
        "summary": {
            "executed": summary.executed,
            "same": summary.same,
            "changed": summary.changed,
            "errors": summary.errors,
        },
        "cases": [_case(result) for result in run.results],
        "validation": {
            "proposed": run.validation.proposed_count,
            "accepted": len(run.validation.accepted),
            "rejected": [
                {"number": item.number, "reason": item.reason, "raw": item.raw}
                for item in run.validation.rejected
            ],
        },
        "limitations": list(LIMITATIONS),
    }
